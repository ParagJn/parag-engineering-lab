@router.post("/{session_id}/feedback/{question_id}", summary="Generate consolidated feedback for a question")
async def get_feedback(
    session_id: str,
    question_id: int,
    agent_svc: AgentService = Depends(get_agent_service),
    session_svc: SessionService = Depends(get_session_service),
):
    session = await session_svc.get_session(session_id)
    if not session:
        raise HTTPException(status_code=404, detail="Session not found")

    question = next((q for q in session.get("questions", []) if q["question_id"] == question_id), None)
    if not question:
        raise HTTPException(status_code=404, detail="Question not found")

    if question.get("status") != "evaluated":
        raise HTTPException(status_code=400, detail="Answer has not been evaluated yet. Please wait.")

    # Return cached feedback if available
    if question.get("consolidated_feedback"):
        return {"feedback": question["consolidated_feedback"], "avg_score": question.get("avg_score")}

    setup = session["setup"]
    feedback = await agent_svc.generate_consolidated_feedback(
        question=question["question"],
        answer=question.get("answer", ""),
        evaluations=question["evaluations"],
        company_name=setup["company_name"],
        job_title=setup["job_title"],
        interview_type=setup["interview_type"],
    )
    await session_svc.set_consolidated_feedback(session_id, question_id, feedback)

    return {"feedback": feedback, "avg_score": question.get("avg_score")}


