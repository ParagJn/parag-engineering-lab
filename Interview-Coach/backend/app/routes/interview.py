@router.post("/{session_id}/answer/{question_id}", summary="Submit an answer and trigger evaluation")
async def submit_answer(
    session_id: str,
    question_id: int,
    request_body: AnswerRequest,
    background_tasks: BackgroundTasks,
    agent_svc: AgentService = Depends(get_agent_service),
    session_svc: SessionService = Depends(get_session_service),
):
    """
    Saves the candidate's answer, then runs all-three-agent evaluation in the background.
    Poll GET /{session_id} to see updated evaluations and status.
    """
    session = await session_svc.get_session(session_id)
    if not session:
        raise HTTPException(status_code=404, detail="Session not found")

    question = next((q for q in session.get("questions", []) if q["question_id"] == question_id), None)
    if not question:
        raise HTTPException(status_code=404, detail="Question not found")

    # Save the answer immediately
    await session_svc.set_question_answer(session_id, question_id, request_body.answer)

    setup = session["setup"]
    background_tasks.add_task(
        _run_evaluation,
        session_id=session_id,
        question_id=question_id,
        question_text=question["question"],
        answer=request_body.answer,
        setup=setup,
        agent_svc=agent_svc,
        session_svc=session_svc,
    )

    return {
        "message": "Answer submitted. Evaluation in progress.",
        "question_id": question_id,
        "status": "evaluating",
    }


async def _run_evaluation(
    session_id: str,
    question_id: int,
    question_text: str,
    answer: str,
    setup: dict,
    agent_svc: AgentService,
    session_svc: SessionService,
):
    try:
        evaluations = await agent_svc.evaluate_answer(
            question=question_text,
            answer=answer,
            company_name=setup["company_name"],
            job_title=setup["job_title"],
            interview_type=setup["interview_type"],
        )
        await session_svc.set_question_evaluations(session_id, question_id, evaluations)
        logger.info("[%s] Q%d evaluated", session_id, question_id)
    except Exception as exc:
        logger.error("[%s] Evaluation for Q%d failed: %s", session_id, question_id, exc, exc_info=True)


