@router.post("/{session_id}/complete", summary="Complete the session and generate a final report")
async def complete_session(
    session_id: str,
    background_tasks: BackgroundTasks,
    agent_svc: AgentService = Depends(get_agent_service),
    session_svc: SessionService = Depends(get_session_service),
):
    session = await session_svc.get_session(session_id)
    if not session:
        raise HTTPException(status_code=404, detail="Session not found")

    # Mark any unanswered/pending questions as 'not_attended'
    questions = session.get("questions", [])
    for q in questions:
        if q.get("status") == "pending":
            q["status"] = "not_attended"

    # Calculate overall score from evaluated questions only
    evaluated = [q for q in questions if q.get("status") == "evaluated" and q.get("avg_score") is not None]
    overall_score = (
        round(sum(q["avg_score"] for q in evaluated) / len(evaluated), 1) if evaluated else None
    )

    await session_svc.update_session(
        session_id,
        {"status": "completed", "overall_score": overall_score, "questions": questions},
    )

    # Generate session summary in the background
    background_tasks.add_task(
        _run_summary,
        session_id=session_id,
        agent_svc=agent_svc,
        session_svc=session_svc,
    )

    return {
        "message": "Session completed. Summary is being generated.",
        "session_id": session_id,
        "overall_score": overall_score,
    }


async def _run_summary(session_id: str, agent_svc: AgentService, session_svc: SessionService):
    try:
        session = await session_svc.get_session(session_id)
        if not session:
            return
        summary = await agent_svc.generate_session_summary(session)
        await session_svc.update_session(session_id, {"session_summary": summary})
        logger.info("[%s] Session summary generated", session_id)
    except Exception as exc:
        logger.error("[%s] Summary generation failed: %s", session_id, exc, exc_info=True)


